-- 10. 节假日配置表 (holiday_data.json)
-- ============================================================
CREATE TABLE `hp_holiday_data` (
  `id`          INT UNSIGNED    NOT NULL AUTO_INCREMENT COMMENT '自增主键',
  `date_key`    VARCHAR(10)     NOT NULL COMMENT '日期键（MM-DD）',
  `date`        DATE            NOT NULL COMMENT '完整日期',
  `name`        VARCHAR(100)    NOT NULL COMMENT '名称',
  `is_holiday`  TINYINT(1)      NOT NULL COMMENT '是否放假',
  `wage`        TINYINT         NOT NULL DEFAULT 1 COMMENT '工资倍数',
  `rest`        INT             NULL     COMMENT '距上一条记录天数',
  `is_after`    TINYINT(1)      NULL     COMMENT '补班是否在节后',
  `target`      VARCHAR(100)    NULL     COMMENT '补班对应的节日',
  `year`        SMALLINT        NOT NULL DEFAULT 2026 COMMENT '所属年份',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_date` (`date`),
  KEY `idx_year_holiday` (`year`, `is_holiday`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='节假日配置表';

