# ======================================
# 节假日配置与判断工具
# ======================================
#
# 功能说明：
#   1. 提供节假日、调休日、工作日的判断函数
#   2. 存储年度节假日数据（关联数组格式）
#   3. 支持多年份数据共存，按年份动态引用
#
# 数据格式：
#   declare -A HOLIDAYS_YYYY=(
#       ['YYYY-MM-DD']='节日名称|类型'
#   )
#   类型说明：2 - 放假 | 3 - 调休上班
#
# 数据来源：
#   - 由 update-tools/generate_holiday_config.sh 自动生成
#   - 原始数据来自国务院官方通知 + 公司HR特别福利
#
# 提供函数：
#   is_holiday <date>        - 判断是否为放假日
#   is_adjust_workday <date> - 判断是否为调休上班日
#   is_workday <date>        - 综合判断是否为工作日
#
# 使用方式：
#   source "${PROJECT_DIR}/holiday_config.sh"
#   is_holiday "2026-01-01" && echo "今天是假期"
#   is_workday "2026-03-10" && echo "今天需要上班"
#
# 作者：智能提醒系统
# 更新：2026-03-10
# ======================================

# ======================================
# 函数名称: is_holiday
# 功能描述: 判断指定日期是否为法定节假日或放假日
# 参数说明:
#   $1 - 待检查的日期（格式：YYYY-MM-DD），可选，默认为当前日期
# 返回值:
#   0 - 是放假日（包括法定节假日、公司特别假等）
#   1 - 不是放假日
# 实现逻辑:
#   1. 获取日期参数，默认使用当前日期
#   2. 提取年份，动态构造对应年份的节假日数组变量名（如 HOLIDAYS_2026）
#   3. 使用 eval 间接引用获取该日期在数组中的值
#   4. 检查值是否存在且以 "|2" 结尾（2 表示放假标记）
# 使用示例:
#   is_holiday "2026-01-01" && echo "今天是假期"
# ======================================
is_holiday() {
    local check_date="${1:-$(date '+%Y-%m-%d')}"
    local year=$(echo "$check_date" | cut -d'-' -f1)
    local var_name="HOLIDAYS_${year}"
    
    # 使用间接引用检查数组元素
    eval "local h_info=\"\${${var_name}[\$check_date]}\""
    [ -n "$h_info" ] && [[ "$h_info" =~ \|2$ ]]
}

# ======================================
# 函数名称: is_adjust_workday
# 功能描述: 判断指定日期是否为调休上班日
# 参数说明:
#   $1 - 待检查的日期（格式：YYYY-MM-DD），可选，默认为当前日期
# 返回值:
#   0 - 是调休上班日（原本是周末，但需要上班补假）
#   1 - 不是调休上班日
# 实现逻辑:
#   1. 获取日期参数，默认使用当前日期
#   2. 提取年份，动态构造对应年份的节假日数组变量名（如 HOLIDAYS_2026）
#   3. 使用 eval 间接引用获取该日期在数组中的值
#   4. 检查值是否存在且以 "|3" 结尾（3 表示调休上班标记）
# 使用示例:
#   is_adjust_workday "2026-01-04" && echo "今天是调休上班日"
# ======================================
is_adjust_workday() {
    local check_date="${1:-$(date '+%Y-%m-%d')}"
    local year=$(echo "$check_date" | cut -d'-' -f1)
    local var_name="HOLIDAYS_${year}"

    # 使用间接引用检查数组元素
    eval "local h_info=\"\${${var_name}[\$check_date]}\""
    if [ -n "$h_info" ] && [[ "$h_info" =~ \|3$ ]]; then
        # 输出节日名称（去掉 |3 后缀），供调用方通过命令替换捕获
        echo "${h_info%|3}"
        return 0
    fi
    return 1
}

# ======================================
# 函数名称: is_workday
# 功能描述: 判断指定日期是否为工作日（综合考虑调休、节假日和周末）
# 参数说明:
#   $1 - 待检查的日期（格式：YYYY-MM-DD），可选，默认为当前日期
# 返回值:
#   0 - 是工作日（需要上班）
#   1 - 不是工作日（休息日）
# 实现逻辑（按优先级判断）:
#   1. 优先级1：如果是调休上班日 → 返回 0（是工作日）
#      即使是周末，只要标记为调休上班，就需要上班
#   2. 优先级2：如果是法定节假日 → 返回 1（不是工作日）
#      即使是周一到周五，只要是节假日就不用上班
#   3. 优先级3：普通日期按星期判断
#      - 获取星期几（1=周一, 7=周日）
#      - 周一到周五（1-5）→ 返回 0（是工作日）
#      - 周六周日（6-7）→ 返回 1（不是工作日）
# 使用示例:
#   is_workday "2026-01-04" && echo "今天需要上班"
#   is_workday "2026-01-01" || echo "今天休息"
# ======================================
is_workday() {
    local check_date="${1:-$(date '+%Y-%m-%d')}"
    # 注意：is_adjust_workday 命中时会向 stdout 输出节日名，这里只关心返回码，必须静默
    is_adjust_workday "$check_date" >/dev/null && return 0
    is_holiday "$check_date" >/dev/null && return 1
    local day=$(date -d "$check_date" '+%u' 2>/dev/null || echo "1")
    [ "$day" -le 5 ]
}

# 计算本周剩余工作日数（不含今天，含调休上班日）
# 使用示例:
#   remaining_workdays_this_week          # 默认今天
#   remaining_workdays_this_week "2026-05-08"
# 返回: stdout 输出剩余工作日天数
remaining_workdays_this_week() {
    local base_date="${1:-$(TZ=Asia/Shanghai date '+%Y-%m-%d')}"
    local dow
    dow=$(date -d "$base_date" '+%u' 2>/dev/null || echo "1")
    local count=0
    local i
    local _old_u=${-//[^u]/}
    set +u
    for i in $(seq 1 $((7 - dow))); do
        local check_date
        check_date=$(date -d "$base_date +${i} days" '+%Y-%m-%d')
        if is_workday "$check_date"; then
            count=$((count + 1))
        fi
    done
    [ -n "$_old_u" ] && set -u
    echo $count
}

# 判断某天是否为本周最后一个工作日
# 使用示例:
#   is_last_workday_of_week && echo "今天是本周最后一个工作日"
#   is_last_workday_of_week "2026-05-09" && echo "5/9是本周最后一个工作日"
# 返回: 0=是最后一个工作日, 1=不是
is_last_workday_of_week() {
    local base_date="${1:-$(TZ=Asia/Shanghai date '+%Y-%m-%d')}"
    local _old_u=${-//[^u]/}
    set +u
    # 今天必须是工作日
    if ! is_workday "$base_date"; then
        [ -n "$_old_u" ] && set -u
        return 1
    fi
    [ -n "$_old_u" ] && set -u
    # 本周剩余天数是否还有工作日
    local remaining
    remaining=$(remaining_workdays_this_week "$base_date")
    [ "$remaining" -eq 0 ]
}

